/*
 * The DAIs of the Google Tensor AoC (audio and sensor DSP), as the one cell
 * of its sound-dai specifier.
 *
 * Bit 31 marks a back end (one of the AoC's ports to a codec, microphone or
 * link), bit 30 a capture stream and bit 29 a front end with no host buffer.
 * The low 16 bits number the AoC entry point or port.
 */

#ifndef _DT_BINDINGS_SOUND_GOOGLE_AOC_H
#define _DT_BINDINGS_SOUND_GOOGLE_AOC_H

#define AOC_DAI_BACK_END			0x80000000
#define AOC_DAI_CAPTURE				0x40000000
#define AOC_DAI_NO_HOST				0x20000000

/* Front ends: the AoC's entry points */
#define AOC_PORT_EP1_PLAYBACK			0x00
#define AOC_PORT_EP2_PLAYBACK			0x01
#define AOC_PORT_EP3_PLAYBACK			0x02
#define AOC_PORT_EP4_PLAYBACK			0x03
#define AOC_PORT_EP5_PLAYBACK			0x04
#define AOC_PORT_EP6_PLAYBACK			0x05
#define AOC_PORT_EP7_PLAYBACK			0x06
#define AOC_PORT_EP8_PLAYBACK			0x07
#define AOC_PORT_NOHOST1_PLAYBACK		(AOC_DAI_NO_HOST | 0x08)
#define AOC_PORT_RAW_PLAYBACK			0x09
#define AOC_PORT_VOIP_PLAYBACK			0x0a
#define AOC_PORT_INCALL0_PLAYBACK		0x0b
#define AOC_PORT_INCALL1_PLAYBACK		0x0c
#define AOC_PORT_HIFI_PLAYBACK			0x10
#define AOC_PORT_HAPTIC_NOHOST_PLAYBACK		(AOC_DAI_NO_HOST | 0x11)
#define AOC_PORT_ULTRASONIC_PLAYBACK		0x13
#define AOC_PORT_INCALL2_PLAYBACK		0x14
#define AOC_PORT_IMMERSIVE_PLAYBACK		0x15
#define AOC_PORT_CAPTURE_INJECT_PLAYBACK	0x16

#define AOC_PORT_EP1_CAPTURE			(AOC_DAI_CAPTURE | 0x00)
#define AOC_PORT_EP2_CAPTURE			(AOC_DAI_CAPTURE | 0x01)
#define AOC_PORT_EP3_CAPTURE			(AOC_DAI_CAPTURE | 0x02)
#define AOC_PORT_EP4_CAPTURE			(AOC_DAI_CAPTURE | 0x03)
#define AOC_PORT_EP5_CAPTURE			(AOC_DAI_CAPTURE | 0x04)
#define AOC_PORT_EP6_CAPTURE			(AOC_DAI_CAPTURE | 0x05)
#define AOC_PORT_NOHOST1_CAPTURE		(AOC_DAI_CAPTURE | AOC_DAI_NO_HOST | 0x08)
#define AOC_PORT_VOIP_CAPTURE			(AOC_DAI_CAPTURE | 0x0a)
#define AOC_PORT_INCALL0_CAPTURE		(AOC_DAI_CAPTURE | 0x0d)
#define AOC_PORT_INCALL1_CAPTURE		(AOC_DAI_CAPTURE | 0x0e)
#define AOC_PORT_INCALL2_CAPTURE		(AOC_DAI_CAPTURE | 0x0f)
#define AOC_PORT_HIFI_CAPTURE			(AOC_DAI_CAPTURE | 0x10)
#define AOC_PORT_ANDROID_AEC_CAPTURE		(AOC_DAI_CAPTURE | 0x12)
#define AOC_PORT_HOTWORD_TAP_CAPTURE		(AOC_DAI_CAPTURE | 0x17)
#define AOC_PORT_INCALL3_CAPTURE		(AOC_DAI_CAPTURE | 0x19)

/* Back ends: the AoC's ports */
#define AOC_PORT_I2S_0_RX		(AOC_DAI_BACK_END | 0x00)
#define AOC_PORT_I2S_0_TX		(AOC_DAI_BACK_END | AOC_DAI_CAPTURE | 0x01)
#define AOC_PORT_I2S_1_RX		(AOC_DAI_BACK_END | 0x02)
#define AOC_PORT_I2S_1_TX		(AOC_DAI_BACK_END | AOC_DAI_CAPTURE | 0x03)
#define AOC_PORT_I2S_2_RX		(AOC_DAI_BACK_END | 0x04)
#define AOC_PORT_I2S_2_TX		(AOC_DAI_BACK_END | AOC_DAI_CAPTURE | 0x05)
#define AOC_PORT_TDM_0_RX		(AOC_DAI_BACK_END | 0x06)
#define AOC_PORT_TDM_0_TX		(AOC_DAI_BACK_END | AOC_DAI_CAPTURE | 0x07)
#define AOC_PORT_TDM_1_RX		(AOC_DAI_BACK_END | 0x08)
#define AOC_PORT_TDM_1_TX		(AOC_DAI_BACK_END | AOC_DAI_CAPTURE | 0x09)
#define AOC_PORT_INTERNAL_MIC_TX	(AOC_DAI_BACK_END | AOC_DAI_CAPTURE | 0x0a)
#define AOC_PORT_BT_RX			(AOC_DAI_BACK_END | 0x0b)
#define AOC_PORT_BT_TX			(AOC_DAI_BACK_END | AOC_DAI_CAPTURE | 0x0c)
#define AOC_PORT_USB_RX			(AOC_DAI_BACK_END | 0x0d)
#define AOC_PORT_USB_TX			(AOC_DAI_BACK_END | AOC_DAI_CAPTURE | 0x0e)
#define AOC_PORT_INCALL_RX		(AOC_DAI_BACK_END | 0x0f)
#define AOC_PORT_INCALL_TX		(AOC_DAI_BACK_END | AOC_DAI_CAPTURE | 0x10)
#define AOC_PORT_HAPTIC_RX		(AOC_DAI_BACK_END | 0x11)
#define AOC_PORT_ERASER_TX		(AOC_DAI_BACK_END | AOC_DAI_CAPTURE | 0x12)
#define AOC_PORT_INTERNAL_MIC_US_TX	(AOC_DAI_BACK_END | AOC_DAI_CAPTURE | 0x13)

#endif /* _DT_BINDINGS_SOUND_GOOGLE_AOC_H */
